/* One-shot migration helper.
 * Usage:
 *   node db-migrate.cjs list-tables            # list tables in SOURCE_DB
 *   node db-migrate.cjs dump-schema            # write schema.json (column defs)
 *   node db-migrate.cjs dump-users             # write users.json (rows)
 *   node db-migrate.cjs apply-schema           # create schema on TARGET_DB (reads schema.json)
 *   node db-migrate.cjs apply-users            # copy users data to TARGET_DB (reads users.json)
 *
 * SOURCE_DB and TARGET_DB are read from env vars.
 */
const fs = require('fs');
const { Pool } = require('pg');

const SOURCE = process.env.SOURCE_DB;
const TARGET = process.env.TARGET_DB;

function pool(conn) {
  if (!conn) throw new Error('connection string missing');
  return new Pool({ connectionString: conn, ssl: { rejectUnauthorized: false } });
}

async function listTables() {
  const p = pool(SOURCE);
  try {
    const r = await p.query(`
      SELECT table_name FROM information_schema.tables
      WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
      ORDER BY table_name;
    `);
    console.log(r.rows.map(x => x.table_name).join('\n'));
  } finally { await p.end(); }
}

async function dumpSchema() {
  const p = pool(SOURCE);
  try {
    const tables = (await p.query(`
      SELECT table_name FROM information_schema.tables
      WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
      ORDER BY table_name;
    `)).rows.map(r => r.table_name);

    const out = { tables: [] };
    for (const table of tables) {
      const cols = (await p.query(`
        SELECT column_name, data_type, udt_name, character_maximum_length,
               is_nullable, column_default, is_identity
        FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = $1
        ORDER BY ordinal_position;
      `, [table])).rows;

      out.tables.push({
        name: table,
        columns: cols.map(c => ({
          name: c.column_name,
          data_type: c.data_type,
          udt_name: c.udt_name,
          char_len: c.character_maximum_length,
          is_nullable: c.is_nullable,
          column_default: c.column_default,
          is_identity: c.is_identity,
        })),
      });
    }
    fs.writeFileSync('schema.json', JSON.stringify(out, null, 2));
    console.log(`Wrote schema.json with ${out.tables.length} tables.`);
  } finally { await p.end(); }
}

async function dumpUsers() {
  const p = pool(SOURCE);
  try {
    const { rows } = await p.query('SELECT * FROM users;');
    const safe = rows.map(r => {
      const o = {};
      for (const k of Object.keys(r)) {
        const v = r[k];
        o[k] = v && typeof v.toISOString === 'function' ? v.toISOString() : v;
      }
      return o;
    });
    fs.writeFileSync('users.json', JSON.stringify(safe, null, 2));
    console.log(`Wrote users.json with ${safe.length} rows.`);
  } finally { await p.end(); }
}

function colType(c) {
  if (c.udt_name.startsWith('_')) {
    const el = c.udt_name.slice(1);
    const map = { text: 'text', int4: 'integer', int8: 'bigint', bool: 'boolean', uuid: 'uuid', jsonb: 'jsonb', json: 'json', varchar: 'character varying', bpchar: 'character', float4: 'real', float8: 'double precision', numeric: 'numeric', timestamptz: 'timestamp with time zone', timestamp: 'timestamp without time zone' };
    return `${map[el] ?? el}[]`;
  }
  if (c.char_len) return `${c.data_type}(${c.char_len})`;
  return c.data_type;
}

async function applySchema() {
  const schema = JSON.parse(fs.readFileSync('schema.json', 'utf8'));
  const dst = pool(TARGET);
  try {
    for (const table of schema.tables) {
      const colDefs = table.columns.map(c => {
        let s = `  "${c.name}" ${colType(c)}`;
        if (c.is_identity === 'YES') s += ' GENERATED BY DEFAULT AS IDENTITY';
        else if (c.column_default) s += ` DEFAULT ${c.column_default}`;
        if (c.is_nullable === 'NO') s += ' NOT NULL';
        return s;
      }).join(',\n');
      const ddl = `CREATE TABLE IF NOT EXISTS "${table.name}" (\n${colDefs}\n);`;
      console.log(`Creating ${table.name}...`);
      await dst.query(ddl);
    }
    console.log('Schema applied.');
  } finally { await dst.end(); }
}

async function applyUsers() {
  const users = JSON.parse(fs.readFileSync('users.json', 'utf8'));
  if (!users.length) { console.log('No users to copy.'); return; }
  const dst = pool(TARGET);
  try {
    const cols = Object.keys(users[0]);
    for (const row of users) {
      const placeholders = cols.map((_, i) => `$${i + 1}`).join(', ');
      const values = cols.map(c => row[c]);
      const sql = `INSERT INTO users (${cols.map(c => `"${c}"`).join(', ')}) VALUES (${placeholders}) ON CONFLICT DO NOTHING;`;
      await dst.query(sql, values);
    }
    console.log(`Copied ${users.length} users.`);
  } finally { await dst.end(); }
}

const cmd = process.argv[2];

(async () => {
  if (cmd === 'list-tables') return listTables();
  if (cmd === 'dump-schema') return dumpSchema();
  if (cmd === 'dump-users') return dumpUsers();
  if (cmd === 'apply-schema') return applySchema();
  if (cmd === 'apply-users') return applyUsers();
  console.error('unknown command:', cmd);
  process.exit(1);
})().catch(e => { console.error(e); process.exit(1); });
